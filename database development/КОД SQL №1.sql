-- Домены и типы удаляются в конце, т.к. таблицы от них зависят
DROP DOMAIN IF EXISTS fio_valid CASCADE;
DROP TYPE IF EXISTS fio_type CASCADE;


CREATE TYPE fio_type AS (
    last_name varchar(50),
    first_name varchar(50),
    middle_name varchar(50)
);

CREATE DOMAIN fio_valid AS fio_type CHECK (
    VALUE IS NULL OR (
        (VALUE).last_name IS NOT NULL AND length(trim((VALUE).last_name)) BETWEEN 1 AND 50 AND
        (VALUE).first_name IS NOT NULL AND length(trim((VALUE).first_name)) BETWEEN 1 AND 50 AND
        ((VALUE).middle_name IS NULL OR length(trim((VALUE).middle_name)) BETWEEN 1 AND 50)
    )
);COMMENT ON DOMAIN fio_valid IS 'Домен для валидации ФИО: обязательны фамилия и имя, отчество опционально, контроль длины 1-50 симв.';


-- УРОВЕНЬ 1: НЕЗАВИСИМЫЕ СПРАВОЧНИКИ

CREATE TABLE IF NOT EXISTS country (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(50) NOT NULL UNIQUE,
    code char(2) NOT NULL UNIQUE,
    CONSTRAINT chk_country_name_len CHECK (length(name) BETWEEN 1 AND 50),
    CONSTRAINT chk_country_code_format CHECK (code ~ '^[A-Z]{2}$')
);

CREATE TABLE IF NOT EXISTS unit (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(30) NOT NULL UNIQUE,
    short_name char(5) NOT NULL UNIQUE,
    CONSTRAINT chk_unit_name_len CHECK (length(name) BETWEEN 1 AND 30),
    CONSTRAINT chk_unit_short_len CHECK (length(short_name) BETWEEN 1 AND 5)
);

CREATE TABLE IF NOT EXISTS category (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(50) NOT NULL UNIQUE,
    CONSTRAINT chk_cat_name_len CHECK (length(name) BETWEEN 1 AND 50)
);

CREATE TABLE IF NOT EXISTS payment_type (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(30) NOT NULL UNIQUE,
    CONSTRAINT chk_pay_name_len CHECK (length(name) BETWEEN 1 AND 30)
);

CREATE TABLE IF NOT EXISTS position (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(50) NOT NULL UNIQUE,
    CONSTRAINT chk_pos_name_len CHECK (length(name) BETWEEN 1 AND 50)
);

CREATE TABLE IF NOT EXISTS loyalty_level (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(30) NOT NULL UNIQUE,
    discount numeric(5, 2) NOT NULL DEFAULT 0.00,
    CONSTRAINT chk_lvl_name_len CHECK (length(name) BETWEEN 1 AND 30),
    CONSTRAINT chk_lvl_discount_range CHECK (discount BETWEEN 0 AND 100)
);
COMMENT ON TABLE loyalty_level IS 'Справочник уровней лояльности с процентом скидки';


-- УРОВЕНЬ 2: ЗАВИСИМЫЕ СПРАВОЧНИКИ И БАЗОВЫЕ ОБЪЕКТЫ

CREATE TABLE IF NOT EXISTS manufacturer (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL UNIQUE,
    country_id int NOT NULL,
    CONSTRAINT chk_manuf_name_len CHECK (length(name) BETWEEN 1 AND 100)
);

CREATE TABLE IF NOT EXISTS store (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL UNIQUE,
    address varchar(200) NOT NULL,
    phone varchar(20),
    CONSTRAINT chk_store_name_len CHECK (length(name) BETWEEN 1 AND 100),
    CONSTRAINT chk_store_addr_len CHECK (length(address) BETWEEN 1 AND 200)
);

CREATE TABLE IF NOT EXISTS supplier (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL UNIQUE,
    inn varchar(12) NOT NULL UNIQUE,
    phone varchar(20),
    address varchar(200),
    CONSTRAINT chk_sup_name_len CHECK (length(name) BETWEEN 1 AND 100),
    CONSTRAINT chk_sup_inn_format CHECK (inn ~ '^[0-9]{10,12}$'),
    CONSTRAINT chk_sup_addr_len CHECK (address IS NULL OR length(address) BETWEEN 1 AND 200)
);

-- В клиенте ФИО опционально (согласно Матрице ПР №2), поэтому NOT NULL не ставим
CREATE TABLE IF NOT EXISTS client (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name fio_valid, -- Опционально: можно передать NULL, домен-проверка будет пропущена
    phone varchar(20) NOT NULL UNIQUE,
    email varchar(255) UNIQUE,
    CONSTRAINT chk_cl_phone_format CHECK (phone ~ '^\+?[0-9\s\-\(\)]{7,20}$'),
    CONSTRAINT chk_cl_email_format CHECK (email IS NULL OR email ~ '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$')
);


-- УРОВЕНЬ 3: КЛЮЧЕВЫЕ ОБЪЕКТЫ

CREATE TABLE IF NOT EXISTS product (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL,
    category_id int NOT NULL,
    manufacturer_id int NOT NULL,
    unit_id int NOT NULL,
    barcode char(13) NOT NULL UNIQUE,
    retail_price numeric(10, 2) NOT NULL DEFAULT 0.00,
    expiration_date date,
    CONSTRAINT chk_prod_name_len CHECK (length(name) BETWEEN 1 AND 100),
    CONSTRAINT chk_prod_barcode_ean13 CHECK (barcode ~ '^[0-9]{13}$'),
    CONSTRAINT chk_prod_price_positive CHECK (retail_price > 0),
    CONSTRAINT chk_prod_expiration_future CHECK (expiration_date IS NULL OR expiration_date > CURRENT_DATE)
);

-- В сотруднике ФИО обязательно (согласно Матрице ПР №2)
CREATE TABLE IF NOT EXISTS employee (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name fio_valid NOT NULL, -- Домен гарантирует валидацию ФИО при каждой вставке
    position_id int NOT NULL,
    store_id int NOT NULL,
    hire_date date NOT NULL DEFAULT CURRENT_DATE,
    password varchar(255) NOT NULL UNIQUE,
    CONSTRAINT chk_emp_hire_not_future CHECK (hire_date <= CURRENT_DATE),
    CONSTRAINT chk_emp_pass_len CHECK (length(password) BETWEEN 1 AND 255)
);

CREATE TABLE IF NOT EXISTS loyalty_card (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number varchar(16) NOT NULL UNIQUE,
    client_id int NOT NULL,
    level_id int NOT NULL,
    issue_date date NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT chk_lc_number_len CHECK (length(number) BETWEEN 10 AND 16)
);


-- УРОВЕНЬ 4: ДОКУМЕНТЫ И РЕГИСТРЫ

CREATE TABLE IF NOT EXISTS inventory (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    store_id int NOT NULL,
    employee_id int NOT NULL,
    actual_stock int NOT NULL DEFAULT 0,
    CONSTRAINT chk_inv_date_not_future CHECK (date <= CURRENT_TIMESTAMP),
    CONSTRAINT chk_inv_stock_non_neg CHECK (actual_stock >= 0)
);

CREATE TABLE IF NOT EXISTS stock (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id int NOT NULL,
    store_id int NOT NULL,
    quantity int NOT NULL DEFAULT 0,
    min_quantity int DEFAULT 0,
    link_inventory_id int,
    CONSTRAINT chk_stock_qty_non_neg CHECK (quantity >= 0),
    CONSTRAINT chk_stock_min_qty_non_neg CHECK (min_quantity IS NULL OR min_quantity >= 0)
);
COMMENT ON TABLE stock IS 'Регистр текущих складских остатков по филиалам';

CREATE TABLE IF NOT EXISTS supply (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number varchar(20) NOT NULL UNIQUE,
    date timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    supplier_id int NOT NULL,
    store_id int NOT NULL,
    summa numeric(10, 2) NOT NULL DEFAULT 0.00,
    CONSTRAINT chk_sup_num_len CHECK (length(number) BETWEEN 1 AND 20),
    CONSTRAINT chk_sup_sum_non_neg CHECK (summa >= 0)
);

CREATE TABLE IF NOT EXISTS sale (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number varchar(20) NOT NULL UNIQUE,
    date timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    employee_id int NOT NULL,
    client_id int,
    payment_type_id int NOT NULL,
    total_amount numeric(10, 2) NOT NULL DEFAULT 0.00,
    CONSTRAINT chk_sale_num_len CHECK (length(number) BETWEEN 1 AND 20),
    CONSTRAINT chk_sale_total_positive CHECK (total_amount > 0)
);
COMMENT ON TABLE sale IS 'Шапка документа кассовой продажи (чека)';

CREATE TABLE IF NOT EXISTS write_off (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number varchar(20) NOT NULL UNIQUE,
    date timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    employee_id int NOT NULL,
    reason varchar(200) NOT NULL,
    CONSTRAINT chk_wo_num_len CHECK (length(number) BETWEEN 1 AND 20),
    CONSTRAINT chk_wo_reason_len CHECK (length(reason) BETWEEN 1 AND 200)
);

CREATE TABLE IF NOT EXISTS return (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number varchar(20) NOT NULL UNIQUE,
    date timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    sale_id int NOT NULL,
    client_id int NOT NULL,
    return_amount numeric(10, 2) NOT NULL DEFAULT 0.00,
    CONSTRAINT chk_ret_num_len CHECK (length(number) BETWEEN 1 AND 20),
    CONSTRAINT chk_ret_amount_positive CHECK (return_amount > 0)
);


-- УРОВЕНЬ 5: ПРОМЕЖУТОЧНЫЕ ТАБЛИЦЫ

CREATE TABLE IF NOT EXISTS supply_item (
    supply_id int NOT NULL,
    product_id int NOT NULL,
    quantity int NOT NULL DEFAULT 1,
    price numeric(10, 2) NOT NULL DEFAULT 0.00,
    PRIMARY KEY (supply_id, product_id),
    CONSTRAINT chk_si_qty_positive CHECK (quantity > 0),
    CONSTRAINT chk_si_price_positive CHECK (price > 0)
);
COMMENT ON TABLE supply_item IS 'Позиции документа поставки';

CREATE TABLE IF NOT EXISTS sale_item (
    sale_id int NOT NULL,
    product_id int NOT NULL,
    quantity int NOT NULL DEFAULT 1,
    price numeric(10, 2) NOT NULL DEFAULT 0.00,
    PRIMARY KEY (sale_id, product_id),
    CONSTRAINT chk_sai_qty_positive CHECK (quantity > 0),
    CONSTRAINT chk_sai_price_positive CHECK (price > 0)
);

CREATE TABLE IF NOT EXISTS write_off_item (
    write_off_id int NOT NULL,
    product_id int NOT NULL,
    quantity int NOT NULL DEFAULT 1,
    PRIMARY KEY (write_off_id, product_id),
    CONSTRAINT chk_woi_qty_positive CHECK (quantity > 0)
);

CREATE TABLE IF NOT EXISTS return_item (
    return_id int NOT NULL,
    product_id int NOT NULL,
    quantity int NOT NULL DEFAULT 1,
    reason varchar(200) NOT NULL,
    PRIMARY KEY (return_id, product_id),
    CONSTRAINT chk_rei_qty_positive CHECK (quantity > 0),
    CONSTRAINT chk_rei_reason_len CHECK (length(reason) BETWEEN 1 AND 200)
);


