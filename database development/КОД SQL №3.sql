SELECT * FROM product;

SELECT 
    s.number AS "Номер чека",
    s.date AS "Дата продажи",
    s.total_amount AS "Сумма, руб."
FROM sale s;

SELECT 
    si.supply_id AS "ID поставки",
    p.name AS "Товар",
    si.quantity AS "Кол-во",
    si.price AS "Цена за ед.",
    si.quantity * si.price AS "Общая стоимость позиции"
FROM supply_item si
JOIN product p ON si.product_id = p.id;

SELECT DISTINCT c.name AS "Страна-производитель"
FROM manufacturer m
JOIN country c ON m.country_id = c.id
ORDER BY c.name;

SELECT 
    p.name AS "Товар",
    p.retail_price AS "Цена",
    c.name AS "Категория",
    m.name AS "Производитель"
FROM product p
JOIN category c ON p.category_id = c.id
JOIN manufacturer m ON p.manufacturer_id = m.id
WHERE (p.name LIKE '%Coca-Cola%' OR p.name LIKE '%Pepsi%')
  AND p.retail_price > 80;

SELECT 
    name AS "Товар",
    retail_price AS "Цена"
FROM product
WHERE retail_price BETWEEN 80 AND 150
ORDER BY retail_price;

SELECT 
    p.name AS "Товар",
    c.name AS "Категория"
FROM product p
JOIN category c ON p.category_id = c.id
WHERE c.name IN ('Газированные напитки', 'Энергетики', 'Вода');

SELECT 
    name AS "Товар",
    retail_price AS "Цена"
FROM product
WHERE name LIKE '%Energy%';

SELECT 
    s.number AS "Номер чека",
    s.date AS "Дата",
    s.total_amount AS "Сумма"
FROM sale s
WHERE s.client_id IS NULL;

SELECT 
    name AS "Товар",
    expiration_date AS "Годен до"
FROM product
WHERE expiration_date IS NOT NULL
ORDER BY expiration_date;

SELECT 
    m.name AS "Производитель",
    COUNT(*) AS "Количество товаров",
    ROUND(AVG(p.retail_price), 2) AS "Средняя цена",
    MIN(p.retail_price) AS "Мин. цена",
    MAX(p.retail_price) AS "Макс. цена"
FROM product p
JOIN manufacturer m ON p.manufacturer_id = m.id
GROUP BY m.name

SELECT 
    s.name AS "Магазин",
    COUNT(i.id) AS "Кол-во инвентаризаций",
    SUM(i.actual_stock) AS "Общий учётный остаток"
FROM inventory i
JOIN store s ON i.store_id = s.id
GROUP BY s.name
HAVING COUNT(i.id) > 3
ORDER BY COUNT(i.id) DESC;

SELECT 
    sup.name AS "Поставщик",
    COUNT(s.id) AS "Кол-во поставок",
    SUM(s.summa) AS "Общая сумма поставок"
FROM supply s
JOIN supplier sup ON s.supplier_id = sup.id
WHERE s.date >= '2024-01-01' AND s.date < '2025-01-01'
GROUP BY sup.name
HAVING SUM(s.summa) > 50000
ORDER BY SUM(s.summa) DESC;

-- Повышаем розничную цену на 10% для всех товаров категории "Вода"
UPDATE product
SET retail_price = retail_price * 1.10
WHERE category_id = (SELECT id FROM category WHERE name = 'Вода');

-- Увеличиваем минимальный остаток на складе для дорогих товаров (> 100 руб.)
UPDATE stock
SET min_quantity = min_quantity + 10
WHERE product_id IN (SELECT id FROM product WHERE retail_price > 100);

-- Удаляем возвраты с маленькой суммой (менее 100 руб.)
DELETE FROM "return"
WHERE return_amount < 100;

-- Удаляем конкретную позицию списания
DELETE FROM write_off_item
WHERE write_off_id = 10 AND product_id = 8;

-- Пытаемся удалить производителя, на которого ссылаются товары
DELETE FROM manufacturer WHERE id = 1;

-- Создаём тестовую таблицу отзывов с каскадным удалением
CREATE TABLE product_reviews (
    review_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INT NOT NULL,
    review_text TEXT NOT NULL,
    rating INT CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT fk_review_product 
        FOREIGN KEY (product_id) 
        REFERENCES product(id) 
        ON DELETE CASCADE
);

